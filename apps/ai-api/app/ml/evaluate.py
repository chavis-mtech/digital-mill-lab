"""`python -m app.ml.evaluate` (make eval): independent re-evaluation of the saved models + generated reports.

1. Reproducibility: reload the saved OER artifact, rebuild the test features from the DB, re-score, compare with the stored MAE.
2. Detections as written: rebuild events from the anomaly_events rows in the DB (detected_at from evidence) and score them
   against injected_events (evaluation only) on the test period - checks the DB content, not the training code path.
3. Writes data/models/EVALUATION.md (all metric tables) and docs/ai/model-cards/<model>.md (SPEC section 9 fields + measured
   numbers), so the published numbers are always the measured ones.
Options: --db-url URL (default settings DATABASE_URL), --no-cards.
"""

from __future__ import annotations

import argparse
import json

import joblib
import pandas as pd

from app.config import REPO_ROOT, get_settings, resolve_database_url
from app.ml import cards
from app.ml.common import MODEL_NAMES, MODEL_VERSION, MODELS_DIR, SPLIT_TS, WINDOW_END, load_metrics, mae, ro_connect
from app.ml.data import load_equipment, load_labels
from app.ml.events import Event, evaluate_events, labels_from_frame


def fmt(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.4g}"
    return str(v)


def table(rows: list[dict], cols: list[str]) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(fmt(r.get(c)) for c in cols) + " |")
    return "\n".join(out)


def reproduce_oer(con) -> dict:
    from app.ml import oer  # noqa: PLC0415

    art = joblib.load(MODELS_DIR / "oer_forecast" / MODEL_VERSION / "model.joblib")
    df = oer.build_frame(con)
    d = oer.model_rows(df).dropna(subset=oer.DELTAS)
    te = d[d.index >= SPLIT_TS]
    got = mae(te["oer_pct"], art["model"].predict(te))
    stored = load_metrics("oer_forecast")["metrics"]["test"][art["served"]]["mae"]
    return {"served": art["served"], "recomputed_test_mae": round(got, 4), "stored_test_mae": stored, "match": abs(got - stored) < 1e-3}


def db_detections(con) -> dict:
    labels = load_labels(con)
    eq = load_equipment(con)
    km = dict(zip(eq["id"].astype(int), eq["code"], strict=True))
    rows = pd.read_sql_query("SELECT domain, detector, equipment_id, start_ts, end_ts, evidence_json FROM anomaly_events WHERE code LIKE 'ANM-%'", con)
    out = {}
    for dom, g in rows.groupby("domain"):
        evs = []
        for r in g.itertuples():
            ev = json.loads(r.evidence_json)
            st = pd.Timestamp(r.start_ts, tz="UTC")
            en = pd.Timestamp(r.end_ts, tz="UTC") if pd.notna(r.end_ts) and r.end_ts else WINDOW_END
            key = km.get(int(r.equipment_id), "") if pd.notna(r.equipment_id) else ""
            if dom == "logistics" and ev.get("truck_trip_id"):
                key = str(ev["truck_trip_id"])
            evs.append(Event(start=st, end=en, detected_at=pd.Timestamp(ev["detected_at"]), peak_ts=st, peak_raw=1, key=key))
        if dom == "production":
            tg = labels[(labels["domain"].isin(["production", "quality"])) | (labels["scenario_code"] == "STEAM_PRESSURE_DEVIATION")]
            m = evaluate_events(evs, labels_from_frame(tg), labels_from_frame(labels), (SPLIT_TS, WINDOW_END), key_match=False, tol_h=6)
        elif dom == "equipment":
            el = labels[labels["equipment_id"].notna()]
            m = evaluate_events(evs, labels_from_frame(el[el["domain"] == "equipment"], km), labels_from_frame(labels, km),
                                (SPLIT_TS, WINDOW_END), tol_h=12)
        elif dom == "energy":
            m = evaluate_events(evs, labels_from_frame(labels[labels["domain"] == "energy"]), labels_from_frame(labels), (SPLIT_TS, WINDOW_END),
                                key_match=False, tol_h=6)
        else:
            lg = labels[(labels["domain"] == "logistics")]
            m = evaluate_events(evs, labels_from_frame(lg), labels_from_frame(labels), (SPLIT_TS, WINDOW_END), key_match=False, tol_h=6)
        out[dom] = {k: m[k] for k in ("events", "precision", "recall", "false_positives_per_day", "median_latency_h", "target_labels")}
        out[dom]["rows_in_db"] = len(g)
    return out


def render_card(name: str, m: dict) -> str:
    c = cards.CARDS[name]
    met = m["metrics"]
    lines = [f"# Model card - `{name}` v{MODEL_VERSION}", "",
             "> Generated by `python -m app.ml.evaluate` from `app/ml/cards.py` + `data/models/" + name + f"/{MODEL_VERSION}/metrics.json`. "
             "Synthetic benchmark - not a real-plant measurement.", "",
             f"**Deployment status:** {c['status']} (demo, synthetic data; advisory only)  ", f"**Algorithm:** {m['algorithm']}  ",
             f"**Task:** {m['task']}  ", f"**Beats baseline (test period):** {m['beats_baseline']}  ",
             f"**Train window:** {m['train_window'][0]} -> {m['train_window'][1]}  ", f"**Test window:** {m['test_window'][0]} -> {m['test_window'][1]}",
             "", "## Purpose", c["purpose"], "", "## Input features", ", ".join(f"`{f}`" for f in m["features"]), "",
             "## Training data", c["training_data"], "", "## Synthetic-data assumptions"]
    lines += [f"- {a}" for a in cards.COMMON_ASSUMPTIONS + c["assumptions"]]
    lines += ["", "## Evaluation method", c["evaluation"], "", "## Validation results (measured)",
              table(m["headline"], ["name", "model", "baseline", "baseline_name", "better_is"]), ""]
    if "test" in met and isinstance(met["test"], dict) and "per_label" not in met["test"]:
        lines += ["Test-period metrics:", "", table([{"model": k, **v} for k, v in met["test"].items() if isinstance(v, dict)],
                                                     ["model", "mae", "rmse"]), ""]
    if "test" in met and isinstance(met["test"], dict) and "per_label" in met["test"]:
        lines += ["Per-label results (test period):", "", table(met["test"]["per_label"], ["label", "kind", "scenario", "entity", "detected",
                                                                                             "latency_h"]), ""]
    if "granularity_comparison" in met:
        rows = []
        for g, v in met["granularity_comparison"].items():
            sel = v["selected_by_cv"]
            rows.append({"granularity": g, "model (CV-selected)": sel, "model_test_mae": v["test"][sel]["mae"],
                         "best_baseline": v["best_baseline_test"], "baseline_test_mae": v["test"][v["best_baseline_test"]]["mae"],
                         "beats": v["beats_best_baseline"]})
        nc = met["nowcast_day"]
        lines += ["## Granularity comparison (test period)", "", table(rows, ["granularity", "model (CV-selected)", "model_test_mae",
                                                                              "best_baseline", "baseline_test_mae", "beats"]), "",
                  f"**Verdict:** {met['granularity_verdict']}", "",
                  f"Day-level nowcast (expected OER given current conditions): residual band +/-{nc['residual_band_pp_90']} pp, "
                  f"test band coverage {nc['test_residual_band_coverage']}, test residual MAE {nc['test_walk_forward_residual_mae']} pp.", ""]
    if name == "logistics_anomaly":
        q = met["queue_window_alerts"]
        lines += ["## Queue alerts (only this detector raises alerts)", "", f"Rule: {q['rule']}. Test: `{q['test']}`. "
                  f"Window check: `{q['window_check']}`.", ""]
    lines += ["## Limitations"] + [f"- {x}" for x in c["limitations"]]
    lines += ["", "## Known failure modes"] + [f"- {x}" for x in c["failure_modes"]]
    lines += ["", "## What is NOT claimed", "- No real-plant accuracy. No calibrated probability. Anomalies are possible contributing factors, "
              "never proven causes; logistics flags are review requests, never accusations.", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db-url", default=None)
    ap.add_argument("--no-cards", action="store_true")
    a = ap.parse_args()
    url = resolve_database_url(a.db_url) if a.db_url else get_settings().database_url
    con = ro_connect(url)
    ms = {n: load_metrics(n) for n in MODEL_NAMES}
    missing = [n for n, m in ms.items() if m is None]
    if missing:
        raise SystemExit(f"missing trained models: {missing} - run `python -m app.ml.train` first")
    rep = reproduce_oer(con)
    print("OER reproducibility:", rep)
    dets = db_detections(con)
    print("Detections as written in the DB (test period):")
    for k, v in dets.items():
        print(f"  {k}: {v}")
    head = [{"model": n, "beats_baseline": m["beats_baseline"], **{f"{h['name']}": f"{fmt(h['model'])} vs {fmt(h['baseline'])} ({h['baseline_name']})"
                                                                  for h in m["headline"][:2]}} for n, m in ms.items()]
    for row in head:
        print(" ", row)
    md = ["# Evaluation report (generated)", "", f"OER reproducibility: `{rep}`", "", "## Detections re-scored from the DB (test period)", "",
          table([{"domain": k, **v} for k, v in dets.items()], ["domain", "rows_in_db", "events", "precision", "recall", "false_positives_per_day",
                                                                "median_latency_h", "target_labels"]), "",
          "## Full metrics per model", ""]
    for n, m in ms.items():
        md += [f"### {n}", "", "```json", json.dumps(m["metrics"], indent=1, default=str)[:20000], "```", ""]
    (MODELS_DIR / "EVALUATION.md").write_text("\n".join(md))
    if not a.no_cards:
        d = REPO_ROOT / "docs" / "ai" / "model-cards"
        d.mkdir(parents=True, exist_ok=True)
        for n, m in ms.items():
            (d / f"{n}.md").write_text(render_card(n, m))
        print(f"wrote {len(ms)} model cards to {d.relative_to(REPO_ROOT)}")
    print(f"wrote {(MODELS_DIR / 'EVALUATION.md').relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
