"""Regenerate apps/ai-api/app/seed/params.py from docs/business/DOMAIN_PARAMETERS.json.

Run from the repo root:  apps/ai-api/.venv/bin/python scripts/seed/snapshot_params.py
Changing the snapshot changes the generated dataset (and its checksum) - re-run `make seed` afterwards.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/business/DOMAIN_PARAMETERS.json"
OUT = ROOT / "apps/ai-api/app/seed/params.py"


def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    lines = [
        f'"""Frozen snapshot of docs/business/DOMAIN_PARAMETERS.json (researcher, v{d["meta"]["version"]}, generated {d["meta"]["generated"]}).',
        "",
        "GENERATED by scripts/seed/snapshot_params.py - do not edit by hand. The generator reads values from here so the",
        "seed does not depend on the docs tree being present (e.g. inside the API Docker image). tests/data/test_params.py",
        "fails if this snapshot drifts from the JSON. Deliberate deviations from the sourced nominal values are listed in",
        "app/seed/assumptions.py (DEVIATIONS) and docs/DATA_GENERATION.md, never by editing this file.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "# key: (nominal, min, max, unit, category, source_id, confidence)",
        "PARAMS: dict[str, tuple] = {",
    ]
    for p in d["parameters"]:
        lines.append(
            f"    {p['key']!r}: ({p['nominal']!r}, {p['min']!r}, {p['max']!r}, {p['unit']!r}, {p['category']!r}, {p['source_id']!r}, {p['confidence']!r}),"
        )
    lines += ["}", "", "PROFILES: dict[str, list] = {"]
    for p in d["profiles"]:
        lines.append(f"    {p['key']!r}: {p['values']!r},")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(d['parameters'])} parameters, {len(d['profiles'])} profiles)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
